export const REGION_PRECEDENCE = Object.freeze(["hollow_abbey", "cinderward", "dunmire", "hearthmere", "graven_march"]);

export function regionAtPosition(x, y) {
  return REGION_PRECEDENCE.map((id) => WORLD.regions.find((region) => region.id === id)).find((region) => {
    const bounds = region.bounds;
    return x >= bounds.x && y >= bounds.y && x < bounds.x + bounds.width && y < bounds.y + bounds.height;
  }) || WORLD.regions[0];
}

